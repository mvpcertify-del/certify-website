-- =====================================================================
-- phase43 — Contractor role: task assignment + evidence submission
-- =====================================================================
--
-- Separate from the structured contract authoring in phase42
-- (contractor_contracts / contractor_contract_signatures): an admin now
-- assigns one or more discrete TASKS to an approved contractor. Per the
-- client's explicit requirement, "Multiple tasks will be assigned per
-- day for each contract" — a contractor may receive several tasks in a
-- single day. The contractor then submits evidence of completed work
-- (a work link, an uploaded file, and/or a short note) from their own
-- dashboard.
--
-- This migration is registration-and-assignment ONLY. Two things are
-- deliberately NOT part of this phase and are not consumed by any code
-- this migration ships with:
--   * Automatic 0%/100% KPI scoring based on deadlines — achieved_percent
--     exists as a column so a later phase can write to it, but nothing
--     here computes it.
--   * Email notifications on assignment/submission/deadline.
--
-- contract_id is nullable on purpose: a task is often tied to a specific
-- signed contract (phase42) so it can be scored against that contract's
-- kpi_definitions, but quick one-off tasks must be assignable to a
-- contractor even before any contract exists for them. kpi_target is
-- free text, not a foreign key, because kpi_definitions on
-- contractor_contracts is a jsonb array, not a row-addressable table —
-- the admin types a label that loosely references one of those entries.
--
-- Same fail-closed RLS pattern as phase41/phase42 (RLS enabled, zero
-- policies, service-role only via api/user.js) — NOT the owner-scoped
-- auditor_documents (phase24) pattern. There is no admin or contractor
-- UI planned yet that queries Supabase directly for this table or
-- bucket.
--
-- Idempotent: safe to run more than once.
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 1. contractor_tasks — one row per assigned task
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.contractor_tasks (
  id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  contractor_id        uuid NOT NULL REFERENCES public.profiles(id),
  -- Optional link to the specific signed contract this task counts
  -- toward. No ON DELETE behavior specified: a contract should not be
  -- deletable out from under a task history, and none of today's code
  -- deletes contractor_contracts rows.
  contract_id          uuid REFERENCES public.contractor_contracts(id),
  assigned_by           uuid NOT NULL REFERENCES public.profiles(id),

  task_description      text NOT NULL,
  -- Free text, admin-typed (e.g. 'Weekly outreach calls — 20/week').
  -- Loosely references an entry in contractor_contracts.kpi_definitions
  -- but is not a foreign key since that column is a jsonb array.
  kpi_target             text,
  deadline_date          date NOT NULL,

  -- Filled in by the contractor at submission time.
  work_link              text,
  completion_date         date,
  evidence_storage_path   text,
  evidence_note           text,

  status                 text NOT NULL DEFAULT 'pending'
                         CHECK (status IN ('pending', 'submitted', 'completed', 'missed')),

  -- Room for future partial-credit scoring; today's (not-yet-built)
  -- scoring logic only ever writes 0 or 100, never 50 — the CHECK
  -- already allows 50 so that a later phase can introduce partial
  -- credit without another migration touching this constraint.
  achieved_percent        integer CHECK (achieved_percent IS NULL OR achieved_percent IN (0, 50, 100)),

  created_at              timestamptz NOT NULL DEFAULT now(),
  updated_at              timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS contractor_tasks_contractor_idx
  ON public.contractor_tasks (contractor_id);

CREATE INDEX IF NOT EXISTS contractor_tasks_status_idx
  ON public.contractor_tasks (status);

CREATE INDEX IF NOT EXISTS contractor_tasks_deadline_idx
  ON public.contractor_tasks (deadline_date);

-- Service-role only (see header). Enabling RLS with no policy blocks
-- every browser-side (anon/authenticated) request by default — fail
-- closed, same as whop_webhook_events (phase40) and the phase41/phase42
-- contractor tables.
ALTER TABLE public.contractor_tasks ENABLE ROW LEVEL SECURITY;

-- ---------------------------------------------------------------------
-- 2. The private `contractor-task-evidence` bucket
-- ---------------------------------------------------------------------
-- Private: evidence files are served only through short-lived signed
-- URLs generated by the service role — same pattern as
-- `contractor-documents` (phase41) and `contractor-contract-pdfs`
-- (phase42). Deliberately no storage.objects policy: the submit-task
-- action in api/user.js is the only writer and uses the service role
-- exclusively, which bypasses RLS/storage policies automatically.
INSERT INTO storage.buckets (id, name, public)
SELECT 'contractor-task-evidence', 'contractor-task-evidence', false
WHERE NOT EXISTS (SELECT 1 FROM storage.buckets WHERE id = 'contractor-task-evidence');

COMMIT;


// A handful of full country names → ISO-2, so a surface that has only the
// display name (not Geoapify's code) can still resolve a dial code. Only the
// names whose formatting differs from a simple lower-case match are listed;
// everything else falls through to a direct ISO2_TO_DIAL check on request.
const NAME_TO_ISO2 = {
  'united arab emirates': 'ae', uae: 'ae',
  'saudi arabia': 'sa', ksa: 'sa',
  'united states': 'us', 'united states of america': 'us', usa: 'us',
  'united kingdom': 'gb', uk: 'gb', 'great britain': 'gb',
  'south korea': 'kr', 'korea, republic of': 'kr',
  'north korea': 'kp',
  'russia': 'ru', 'russian federation': 'ru',
  'ivory coast': 'ci', "côte d'ivoire": 'ci',
  'czech republic': 'cz', czechia: 'cz',
  'democratic republic of the congo': 'cd',
  'republic of the congo': 'cg', congo: 'cg',
};

// Resolve a dial code from Geoapify's `country_code` (preferred) or a country
// name. Returns null when nothing matches, so callers can leave the user's
// current selection untouched rather than guessing.
export function dialCodeForCountry({ countryCode, countryName } = {}) {
  if (countryCode) {
    const hit = ISO2_TO_DIAL[String(countryCode).trim().toLowerCase()];
    if (hit) return hit;
  }
  if (countryName) {
    const n = String(countryName).trim().toLowerCase();
    const iso = NAME_TO_ISO2[n] || (n.length === 2 ? n : null);
    if (iso && ISO2_TO_DIAL[iso]) return ISO2_TO_DIAL[iso];
  }
  return null;
}

import { useState, useEffect, useCallback } from 'react';
import { useTranslation } from 'react-i18next';
import { useAuth } from '../../contexts/AuthContext';
import { supabase } from '../../lib/supabase';
import { apiPost } from '../../lib/apiClient';
import { Input, Button } from '../../components/ui/FormElements';
import { ISO_CATALOG_LIST, getIsoBySlug } from '../../utils/isoCatalog';
import {
  Mail, FileText, Building2, Paperclip, Download, Send,
  AlertCircle, CheckCircle, Ticket, Check,
} from 'lucide-react';
import './ReferralMarketing.css';

// Marketing Tools — the tick-and-send composer (client, 7 Sep).
//
//   "Marketing tools box which they can open & see all the marketing links
//    (1. Ready Email template + 2. Company Profile to be attached to email +
//    3. ISO Standard Brochure to be selected to attach). For example if ISO
//    9001 is selected to send to client so the above 3 items will be available
//    & just to be ticked & system will send directly"
//
// One screen, because the three items are not three separate errands — they are
// three parts of one letter, and the only question worth asking a partner is
// "which of these goes to this client, now". Splitting the library from the
// send would put the partner back where they started on 6 Sep: able to see that
// a document exists but not to do anything with it.
//
// The Auto Proposal box on the dashboard opens this same screen. It is the same
// action — a proposal, generated by the platform, carrying the partner's
// discount code — and giving it a second screen would mean two composers to
// keep in step.

// The reserved slug the company profile is stored under. Mirrors
// COMPANY_PROFILE_SLUG in api/_assetSlugs.js; it is a constant of the data, not
// a setting, so it is written out here rather than fetched. The browser and the
// server must agree on it — if that ever changes, both ends change together.
const COMPANY_PROFILE_SLUG = 'company-profile';

export default function ReferralMarketing() {
  const { user } = useAuth();
  const { t } = useTranslation();

  const [leads, setLeads] = useState([]);
  const [assets, setAssets] = useState([]);
  const [loading, setLoading] = useState(true);

  const [leadId, setLeadId] = useState('');
  const [standard, setStandard] = useState('');
  const [existingCert, setExistingCert] = useState('');

  // Item 1 is not a checkbox with a false state: the ready email template IS
  // the letter. An email with no body is not something to offer, so it is shown
  // ticked and locked rather than pretended to be optional.
  const [withProfile, setWithProfile] = useState(true);
  const [withBrochure, setWithBrochure] = useState(true);

  const [sending, setSending] = useState(false);
  const [busySlug, setBusySlug] = useState('');
  const [error, setError] = useState('');
  const [success, setSuccess] = useState('');
  const [notice, setNotice] = useState('');

  // Every invite and proposal carries the partner's code. A partner whose row
  // predates phase25 has none, and must be told before they compose a letter
  // rather than after they press send.
  const codeReady = Boolean(user?.referral_code);

  // A partner still awaiting approval can open every screen but cannot send:
  // the server refuses on `partnerActive` (api/referrals.js). Saying so up
  // front is the whole point — the alternative is a partner composing a letter,
  // pressing send, and being told "Forbidden", which is what "the partner can't
  // access it" looks like from the outside.
  const awaitingApproval = user?.approval_status === 'pending';

  const load = useCallback(async () => {
    if (!user?.id) return;
    setLoading(true);

    // The partner's own leads. A converted client has already bought, so
    // pitching them a standard they are mid-certification on reads as a
    // mistake — the same rule the Clients table applies to its send buttons.
    const leadsPromise = supabase
      .from('referrals')
      .select('id, referred_name, referred_company, referred_email, status')
      .eq('referrer_id', user.id)
      .neq('status', 'converted')
      .order('created_at', { ascending: false })
      .then(({ data, error: err }) => (err ? [] : (data || [])), () => []);

    const assetsPromise = apiPost('/api/outreach-assets', { action: 'partner-list' })
      .then((r) => r?.assets || [], () => []);

    const [leadRows, assetRows] = await Promise.all([leadsPromise, assetsPromise]);
    setLeads(leadRows);
    setAssets(assetRows);
    setLoading(false);
  }, [user?.id]);

  useEffect(() => { load(); }, [load]);

  const assetFor = (slug) => assets.find(a => a.standard_slug === slug) || null;
  const companyProfile = assetFor(COMPANY_PROFILE_SLUG);
  const brochure = standard ? assetFor(standard) : null;

  // Brochures only — the company profile is listed separately above and would
  // otherwise appear twice, once as itself and once as an "ISO standard".
  const brochureAssets = assets.filter(a => a.standard_slug !== COMPANY_PROFILE_SLUG);

  const selectedLead = leads.find(l => l.id === leadId) || null;

  const handleDownload = async (slug) => {
    setBusySlug(slug);
    setError('');
    try {
      const { url } = await apiPost('/api/outreach-assets', {
        action: 'partner-download',
        standardSlug: slug,
      });
      window.open(url, '_blank', 'noopener');
    } catch (err) {
      setError(err.message || t('refMarketing.downloadFailed'));
    } finally {
      setBusySlug('');
    }
  };

  const handleSend = async () => {
    if (!leadId || !standard) return;
    if (!codeReady) { setSuccess(''); setError(t('referrals.codePending')); return; }

    // What is BOTH ticked and actually available. The two checkboxes stay true
    // in state when their file is missing — that is what makes the tick come
    // back if the administrator uploads one — so asking for a file that is not
    // there would count as a request the server could never satisfy, and the
    // partner would be told an attachment went missing on every single send.
    const sendProfile = Boolean(companyProfile) && withProfile;
    const sendBrochure = Boolean(brochure) && withBrochure;

    setSending(true);
    setError('');
    setSuccess('');
    setNotice('');
    try {
      const res = await apiPost('/api/referrals', {
        action: 'send-outreach',
        referralId: leadId,
        standardSlug: standard,
        existingCert: existingCert.trim() || null,
        // Only what the partner actually ticked. The server re-checks that the
        // bytes exist before the letter mentions either file, so a tick on
        // something that has since been deleted downgrades the letter rather
        // than making it lie.
        include: {
          brochure: sendBrochure,
          companyProfile: sendProfile,
        },
      });

      setSuccess(t('refMarketing.sent', { email: selectedLead?.referred_email || '' }));

      // The server is the authority on what actually went with the letter. It
      // matters: the partner is about to follow this up with a phone call
      // referring to "the profile I sent you".
      const asked = (sendBrochure ? 1 : 0) + (sendProfile ? 1 : 0);
      const got = res?.attachedCount ?? 0;
      if (got < asked) setNotice(t('refMarketing.someMissing', { asked, got }));

      setLeadId('');
      setExistingCert('');
    } catch (err) {
      setError(err.message || t('refMarketing.sendFailed'));
    } finally {
      setSending(false);
    }
  };

  const canSend = Boolean(leadId && standard) && !sending && !awaitingApproval;

  return (
    <div className="page-container">
      <div className="page-header">
        <div>
          <h1 className="page-title">{t('refDash.marketing')}</h1>
          <p className="page-subtitle">{t('refDash.marketingDesc')}</p>
        </div>
      </div>

      {success && (
        <div className="admin-users__success">
          <CheckCircle size={16} />
          <span>{success}</span>
        </div>
      )}

      {notice && (
        <div className="referrals__notice">
          <AlertCircle size={16} />
          <span>{notice}</span>
        </div>
      )}

      {error && (
        <div className="admin-users__error">
          <AlertCircle size={16} />
          <span>{error}</span>
        </div>
      )}

      {awaitingApproval && (
        <div className="referrals__notice">
          <AlertCircle size={16} />
          <span>{t('refMarketing.approvalPending')}</span>
        </div>
      )}

      {/* ---- The composer ---- */}
      <div className="refmkt__panel">
        <h3 className="refmkt__panel-title">{t('refMarketing.composeTitle')}</h3>
        <p className="refmkt__panel-hint">{t('refMarketing.composeHint')}</p>

        <label className="refmkt__label" htmlFor="mkt-lead">
          {t('refMarketing.chooseClient')}
        </label>
        <select
          id="mkt-lead"
          className="refmkt__select"
          value={leadId}
          onChange={(e) => setLeadId(e.target.value)}
          disabled={loading}
        >
          <option value="">{t('refMarketing.chooseClientPlaceholder')}</option>
          {leads.map((l) => (
            <option key={l.id} value={l.id}>
              {(l.referred_company || l.referred_name || l.referred_email)} — {l.referred_email}
            </option>
          ))}
        </select>
        {!loading && leads.length === 0 && (
          <p className="refmkt__hint">{t('refMarketing.noLeads')}</p>
        )}

        <label className="refmkt__label" htmlFor="mkt-standard">
          {t('refMarketing.chooseStandard')}
        </label>
        <select
          id="mkt-standard"
          className="refmkt__select"
          value={standard}
          onChange={(e) => setStandard(e.target.value)}
        >
          <option value="">{t('refMarketing.chooseStandardPlaceholder')}</option>
          {ISO_CATALOG_LIST.map((iso) => (
            <option key={iso.slug} value={iso.slug}>
              {iso.code} — {t(iso.titleKey)}
            </option>
          ))}
        </select>

        {/* ---- The three items ----
            Drawn as boxes rather than a list of checkbox rows, on the client's
            instruction of 8 Sep: the dashboard's boxes are the visual idea a
            partner already understands, so the three things that go in the
            envelope use it too. Each box is the tick — the whole card is the
            hit target, not a 13px square. */}
        <div className="refmkt__items">
          <div className="refmkt__items-title">{t('refMarketing.itemsTitle')}</div>
          <div className="refmkt__item-grid">
            {[
              {
                key: 'template',
                Icon: Mail,
                color: '#0ea5e9',
                label: t('refMarketing.itemTemplate'),
                note: t('refMarketing.itemTemplateNote'),
                // Not a choice: the ready email template IS the letter, so it
                // is shown on and locked rather than pretended to be optional.
                on: true,
                locked: true,
                available: true,
              },
              {
                key: 'profile',
                Icon: Building2,
                color: '#6366f1',
                label: t('refMarketing.itemProfile'),
                note: companyProfile
                  ? companyProfile.file_name
                  : t('refMarketing.itemProfileMissing'),
                on: Boolean(companyProfile) && withProfile,
                available: Boolean(companyProfile),
                toggle: () => setWithProfile(v => !v),
              },
              {
                key: 'brochure',
                Icon: FileText,
                color: '#f97316',
                label: t('refMarketing.itemBrochure'),
                note: !standard
                  ? t('refMarketing.itemBrochurePickFirst')
                  : brochure
                    ? brochure.file_name
                    : t('refMarketing.itemBrochureMissing'),
                on: Boolean(brochure) && withBrochure,
                available: Boolean(brochure),
                toggle: () => setWithBrochure(v => !v),
              },
            ].map(item => (
              <button
                key={item.key}
                type="button"
                className={`refmkt__item${item.on ? ' refmkt__item--on' : ''}`
                  + `${item.available ? '' : ' refmkt__item--off'}`}
                style={{ '--item-accent': item.color }}
                // A locked item is still rendered as pressed, so the partner
                // can see it is going; it just cannot be un-pressed.
                aria-pressed={item.on}
                disabled={item.locked || !item.available}
                onClick={item.toggle}
              >
                <span
                  className="refmkt__item-icon"
                  style={{ background: `${item.color}1a`, color: item.color }}
                >
                  <item.Icon size={20} />
                </span>
                <span className="refmkt__item-tick" aria-hidden="true">
                  {item.on ? <Check size={14} /> : null}
                </span>
                <span className="refmkt__item-label">{item.label}</span>
                <span className="refmkt__item-note">{item.note}</span>
              </button>
            ))}
          </div>
        </div>

        <Input
          label={t('referrals.proposalExisting')}
          id="mkt-existing"
          name="mkt_existing"
          placeholder={t('referrals.proposalExistingPlaceholder')}
          value={existingCert}
          onChange={(e) => setExistingCert(e.target.value)}
          maxLength={60}
        />
        <p className="refmkt__hint">{t('referrals.proposalExistingHint')}</p>

        {/* The discount code is not a tick box — it is always in the letter.
            Saying so is the point: the client asked for the proposal to carry
            it, and a partner needs to know it is there without being able to
            switch it off by accident. */}
        <p className="refmkt__code-note">
          <Ticket size={14} />
          <span>
            {codeReady
              ? t('refMarketing.codeIncluded', { code: user.referral_code })
              : t('referrals.codePending')}
          </span>
        </p>

        <div className="refmkt__actions">
          <Button
            variant="primary"
            size="md"
            loading={sending}
            disabled={!canSend}
            onClick={handleSend}
          >
            <Send size={16} /> {t('refMarketing.send')}
          </Button>
        </div>
      </div>

      {/* ---- The library ---- */}
      <div className="refmkt__panel">
        <h3 className="refmkt__panel-title">{t('refMarketing.libraryTitle')}</h3>
        <p className="refmkt__panel-hint">{t('refMarketing.libraryHint')}</p>

        {loading ? (
          <p className="refmkt__hint">{t('common.loading')}</p>
        ) : (
          <div className="refmkt__library">
            <div className="refmkt__doc">
              <div className="refmkt__doc-icon"><Building2 size={20} /></div>
              <div className="refmkt__doc-body">
                <div className="refmkt__doc-name">{t('refMarketing.itemProfile')}</div>
                <div className="refmkt__doc-meta">
                  {companyProfile ? companyProfile.file_name : t('refMarketing.itemProfileMissing')}
                </div>
              </div>
              {companyProfile && (
                <Button
                  size="sm"
                  variant="outline"
                  loading={busySlug === COMPANY_PROFILE_SLUG}
                  onClick={() => handleDownload(COMPANY_PROFILE_SLUG)}
                >
                  <Download size={15} /> {t('common.download')}
                </Button>
              )}
            </div>

            {brochureAssets.length === 0 ? (
              <p className="refmkt__hint">{t('referrals.materialsEmpty')}</p>
            ) : (
              brochureAssets.map((a) => {
                const iso = getIsoBySlug(a.standard_slug);
                return (
                  <div className="refmkt__doc" key={a.standard_slug}>
                    <div className="refmkt__doc-icon"><FileText size={20} /></div>
                    <div className="refmkt__doc-body">
                      <div className="refmkt__doc-name">
                        {iso?.code || a.standard_slug}
                        {iso?.titleKey ? ` — ${t(iso.titleKey)}` : ''}
                      </div>
                      <div className="refmkt__doc-meta">{a.file_name}</div>
                    </div>
                    <Button
                      size="sm"
                      variant="outline"
                      loading={busySlug === a.standard_slug}
                      onClick={() => handleDownload(a.standard_slug)}
                    >
                      <Download size={15} /> {t('common.download')}
                    </Button>
                  </div>
                );
              })
            )}
          </div>
        )}

        <p className="refmkt__attach-note">
          <Paperclip size={14} />
          <span>{t('referrals.materialsHint')}</span>
        </p>
      </div>
    </div>
  );
}

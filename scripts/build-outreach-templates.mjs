// Turns the three approved marketing emails (marketing-emails/0*.html) into api/_outreachTemplates.js.
// A serverless function cannot rely on reading those files at run time, so the text is baked into a module.
//   node scripts/build-outreach-templates.mjs
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const files = [
  ['1', '01-introduction.html'],
  ['2', '02-follow-up-day-4.html'],
  ['3', '03-final-follow-up-day-9.html'],
];

const out = {};
for (const [step, name] of files) {
  const raw = fs.readFileSync(path.join(ROOT, 'marketing-emails', name), 'utf8');
  const subject = (raw.match(/^\s*Subject:\s*(.+)$/m) || [])[1];
  if (!subject) throw new Error(`${name}: no "Subject:" line in the header comment`);
  const html = raw.replace(/^<!--[\s\S]*?-->\s*/, '');
  out[step] = { subject: subject.trim(), html };
}

const body = `// GENERATED by scripts/build-outreach-templates.mjs from marketing-emails/*.html. Do not edit by hand:
// change the HTML files and run the script again.
export const TEMPLATES = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(path.join(ROOT, 'api', '_outreachTemplates.js'), body);
console.log('wrote api/_outreachTemplates.js', Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.subject])));

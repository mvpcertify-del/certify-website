// Builds supabase/phase51_chart_of_accounts.sql from api/_coaMaster.js.
//   node scripts/build-coa-sql.mjs
// The account list is generated, never hand-typed, so the database cannot drift from the approved V1.0 list.
import { writeFileSync } from 'node:fs';
import { ACCOUNTS, COA_VERSION, COA_TITLE } from '../api/_coaMaster.js';

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const b = (v) => (v ? 'true' : 'false');

const rows = ACCOUNTS.map((a) => `  (${q(a.code)}, ${q(a.name)}, ${q(a.category)}, ${q(a.parent)}, ${q(a.normal)}, ${b(a.isHeader)}, ${b(a.isContra)}, ${b(a.allowPosting)}, ${q(a.ifrs)})`).join(',\n');

const sql = `-- Phase 51: Finance ERP, Master Chart of Accounts ${COA_VERSION} (IFRS edition), general ledger tables and rules.
-- Generated by scripts/build-coa-sql.mjs from api/_coaMaster.js. Safe to run more than once.
--
-- What this creates
--   fin_entities          legal entities (each has its own ledger)
--   coa_versions          revisions of the chart. ${COA_VERSION} is active. The next revision is V1.1, never an overwrite.
--   coa_accounts          the chart: code, name, category, parent, normal balance (Dr/Cr), currency, entity, department,
--                         cost centre, project, tax treatment, IFRS 18 class, active flag, posting permission
--   coa_audit             history of every change to an account
--   fin_journal_entries   double-entry journals (unique reference, draft -> posted -> reversed)
--   fin_journal_lines     debit/credit lines
--   coa_balances (view)   balance of every account from POSTED lines. With no postings every balance is zero.
-- Rules enforced by the database
--   * an entry cannot be posted unless total debits equal total credits (and are not zero)
--   * a posted or reversed entry and its lines cannot be changed or deleted; correct with a reversal entry
--   * a line can only be posted to an active, postable (non-group) account, one side only (debit or credit)
--   * every table is service-role only (RLS on, no policies)

-- ---------------------------------------------------------------- entities and versions
CREATE TABLE IF NOT EXISTS public.fin_entities (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  code          text NOT NULL UNIQUE,
  name          text NOT NULL,
  base_currency text NOT NULL DEFAULT 'USD' CHECK (base_currency ~ '^[A-Z]{3}$'),
  is_active     boolean NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.coa_versions (
  version     text PRIMARY KEY,
  status      text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'active', 'superseded')),
  title       text,
  notes       text,
  approved_at timestamptz,
  created_at  timestamptz NOT NULL DEFAULT now()
);

INSERT INTO public.coa_versions (version, status, title, notes, approved_at)
VALUES (${q(COA_VERSION)}, 'active', ${q(COA_TITLE)},
        'Approved development baseline. IFRS does not prescribe one universal chart: validate against the legal entities, tax jurisdictions and final IFRS reporting policies before production posting.',
        now())
ON CONFLICT (version) DO NOTHING;

INSERT INTO public.fin_entities (code, name, base_currency)
VALUES ('CIOPC', 'Certify International OPC Private Limited', 'USD')
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------- the chart
CREATE TABLE IF NOT EXISTS public.coa_accounts (
  code          text PRIMARY KEY CHECK (code ~ '^[1-9][0-9]{3}$'),
  name          text NOT NULL,
  category      text NOT NULL CHECK (category IN ('asset', 'liability', 'equity', 'revenue', 'cost_of_revenue', 'expense', 'finance_other', 'oci', 'control')),
  parent_code   text REFERENCES public.coa_accounts (code),
  normal_balance text NOT NULL CHECK (normal_balance IN ('Dr', 'Cr', 'Dr/Cr')),
  is_header     boolean NOT NULL DEFAULT false,
  is_contra     boolean NOT NULL DEFAULT false,
  allow_posting boolean NOT NULL DEFAULT true,
  is_active     boolean NOT NULL DEFAULT true,
  currency      text CHECK (currency IS NULL OR currency ~ '^[A-Z]{3}$'),   -- NULL = any currency
  entity_id     uuid REFERENCES public.fin_entities (id),                   -- NULL = every entity
  department    text,
  cost_centre   text,
  project       text,
  tax_treatment text,
  ifrs_class    text NOT NULL DEFAULT 'none' CHECK (ifrs_class IN ('operating', 'investing', 'financing', 'income_tax', 'discontinued', 'oci', 'none')),
  introduced_in text NOT NULL DEFAULT ${q(COA_VERSION)} REFERENCES public.coa_versions (version),
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  updated_by    uuid
);
CREATE INDEX IF NOT EXISTS coa_accounts_parent_idx ON public.coa_accounts (parent_code);

CREATE TABLE IF NOT EXISTS public.coa_audit (
  id           bigserial PRIMARY KEY,
  account_code text NOT NULL,
  action       text NOT NULL,
  before       jsonb,
  after        jsonb,
  actor        uuid,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS coa_audit_account_idx ON public.coa_audit (account_code, created_at DESC);

-- ---------------------------------------------------------------- journals
CREATE TABLE IF NOT EXISTS public.fin_journal_entries (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  entity_id   uuid NOT NULL REFERENCES public.fin_entities (id),
  reference   text NOT NULL UNIQUE,
  entry_date  date NOT NULL DEFAULT current_date,
  description text,
  currency    text NOT NULL DEFAULT 'USD' CHECK (currency ~ '^[A-Z]{3}$'),
  status      text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'posted', 'reversed')),
  source      text,
  reverses_id uuid REFERENCES public.fin_journal_entries (id),
  created_by  uuid,
  created_at  timestamptz NOT NULL DEFAULT now(),
  posted_at   timestamptz,
  posted_by   uuid
);

CREATE TABLE IF NOT EXISTS public.fin_journal_lines (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  entry_id        uuid NOT NULL REFERENCES public.fin_journal_entries (id) ON DELETE CASCADE,
  account_code    text NOT NULL REFERENCES public.coa_accounts (code),
  debit           numeric(18, 2) NOT NULL DEFAULT 0 CHECK (debit >= 0),
  credit          numeric(18, 2) NOT NULL DEFAULT 0 CHECK (credit >= 0),
  currency        text NOT NULL DEFAULT 'USD' CHECK (currency ~ '^[A-Z]{3}$'),
  fx_rate         numeric(18, 8) NOT NULL DEFAULT 1 CHECK (fx_rate > 0),
  amount_original numeric(18, 2),
  department      text,
  cost_centre     text,
  project         text,
  memo            text,
  CONSTRAINT fin_journal_one_side CHECK ((debit > 0 AND credit = 0) OR (credit > 0 AND debit = 0))
);
CREATE INDEX IF NOT EXISTS fin_journal_lines_entry_idx ON public.fin_journal_lines (entry_id);
CREATE INDEX IF NOT EXISTS fin_journal_lines_account_idx ON public.fin_journal_lines (account_code);

-- An entry: balanced to post, immutable once posted, never deleted once posted.
CREATE OR REPLACE FUNCTION public.fin_entry_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  d numeric;
  c numeric;
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.status IN ('posted', 'reversed') THEN
      RAISE EXCEPTION 'Posted journal entries cannot be deleted. Post a reversal entry instead.';
    END IF;
    RETURN OLD;
  END IF;

  IF OLD.status IN ('posted', 'reversed') THEN
    IF NEW.status = 'draft' OR (OLD.status = 'reversed' AND NEW.status <> 'reversed') THEN
      RAISE EXCEPTION 'A posted journal entry cannot be reopened. Post a reversal entry instead.';
    END IF;
    IF NEW.reference IS DISTINCT FROM OLD.reference OR NEW.entry_date IS DISTINCT FROM OLD.entry_date
       OR NEW.entity_id IS DISTINCT FROM OLD.entity_id OR NEW.currency IS DISTINCT FROM OLD.currency THEN
      RAISE EXCEPTION 'A posted journal entry cannot be changed. Post a reversal entry instead.';
    END IF;
  END IF;

  IF NEW.status = 'posted' AND OLD.status = 'draft' THEN
    SELECT COALESCE(SUM(debit), 0), COALESCE(SUM(credit), 0) INTO d, c FROM public.fin_journal_lines WHERE entry_id = NEW.id;
    IF d = 0 OR d <> c THEN
      RAISE EXCEPTION 'The journal entry is not balanced (debits %, credits %). It cannot be posted.', d, c;
    END IF;
    NEW.posted_at := now();
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS fin_entry_guard_trg ON public.fin_journal_entries;
CREATE TRIGGER fin_entry_guard_trg BEFORE UPDATE OR DELETE ON public.fin_journal_entries
  FOR EACH ROW EXECUTE FUNCTION public.fin_entry_guard();

-- A line: only on a draft entry, only to an active postable account.
CREATE OR REPLACE FUNCTION public.fin_line_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  st text;
  acc record;
BEGIN
  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    SELECT status INTO st FROM public.fin_journal_entries WHERE id = OLD.entry_id;
    IF st IN ('posted', 'reversed') THEN
      RAISE EXCEPTION 'Lines of a posted journal entry cannot be changed or deleted. Post a reversal entry instead.';
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  END IF;

  SELECT status INTO st FROM public.fin_journal_entries WHERE id = NEW.entry_id;
  IF st IS DISTINCT FROM 'draft' THEN
    RAISE EXCEPTION 'Lines can only be added to a draft journal entry.';
  END IF;
  SELECT is_active, allow_posting, is_header INTO acc FROM public.coa_accounts WHERE code = NEW.account_code;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Account % does not exist.', NEW.account_code;
  END IF;
  IF acc.is_header OR NOT acc.allow_posting OR NOT acc.is_active THEN
    RAISE EXCEPTION 'Account % cannot be posted to (group, inactive or posting not allowed).', NEW.account_code;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS fin_line_guard_trg ON public.fin_journal_lines;
CREATE TRIGGER fin_line_guard_trg BEFORE INSERT OR UPDATE OR DELETE ON public.fin_journal_lines
  FOR EACH ROW EXECUTE FUNCTION public.fin_line_guard();

-- Balance of every account from posted (and later reversed) entries only.
CREATE OR REPLACE VIEW public.coa_balances AS
SELECT a.code,
       COALESCE(SUM(l.debit), 0)::numeric(18, 2)  AS debit_total,
       COALESCE(SUM(l.credit), 0)::numeric(18, 2) AS credit_total
FROM public.coa_accounts a
LEFT JOIN (
  SELECT jl.account_code, jl.debit, jl.credit
  FROM public.fin_journal_lines jl
  JOIN public.fin_journal_entries je ON je.id = jl.entry_id AND je.status IN ('posted', 'reversed')
) l ON l.account_code = a.code
GROUP BY a.code;

-- ---------------------------------------------------------------- access: service role only
ALTER TABLE public.fin_entities        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.coa_versions        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.coa_accounts        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.coa_audit           ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fin_journal_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fin_journal_lines   ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.coa_balances FROM anon, authenticated;

-- ---------------------------------------------------------------- the chart ${COA_VERSION}: ${ACCOUNTS.length} rows (${ACCOUNTS.filter((a) => a.isHeader).length} groups, ${ACCOUNTS.filter((a) => !a.isHeader).length} accounts)
INSERT INTO public.coa_accounts (code, name, category, parent_code, normal_balance, is_header, is_contra, allow_posting, ifrs_class)
VALUES
${rows}
ON CONFLICT (code) DO NOTHING;
`;


// Turns scripts/affiliateTrainingContent.mjs into supabase/phase55_seed_training.sql, so the training can be loaded from the
// Supabase SQL editor without a service-role key on this machine. Safe to re-run: the SQL upserts by slug.
//   node scripts/build-training-seed-sql.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { MODULES } from './affiliateTrainingContent.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const lit = (v) => `$j$${JSON.stringify(v)}$j$`;           // dollar-quoted JSON: no escaping problems with apostrophes
const txt = (v) => `$t$${String(v)}$t$`;

const rows = MODULES.map((m) =>
  `  (${txt(m.slug)}, ${m.position}, ${txt(m.title)}, ${txt(m.summary)}, ${m.minutes}, ${lit(m.lessons)}::jsonb, ${lit(m.quiz)}::jsonb, true, now())`
).join(',\n');

const sql = `-- Affiliate training content for Certify.wiki(TM). Generated by scripts/build-training-seed-sql.mjs from
-- scripts/affiliateTrainingContent.mjs. Run AFTER phase55_affiliate_training.sql. Safe to run more than once.
INSERT INTO public.training_modules (slug, position, title, summary, minutes, lessons, quiz, published, updated_at)
VALUES
${rows}
ON CONFLICT (slug) DO UPDATE SET
  position = EXCLUDED.position, title = EXCLUDED.title, summary = EXCLUDED.summary, minutes = EXCLUDED.minutes,
  lessons = EXCLUDED.lessons, quiz = EXCLUDED.quiz, published = EXCLUDED.published, updated_at = now();
`;
const out = path.join(root, 'supabase', 'phase55_seed_training.sql');
fs.writeFileSync(out, sql);
console.log(`Wrote ${out} (${MODULES.length} modules, ${(sql.length / 1024).toFixed(1)} KB)`);
